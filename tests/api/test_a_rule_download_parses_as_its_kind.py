"""``/signatures/{kind}`` serves a file of its kind, and by default only what the report prints.

The download put ``// <name>`` before every body and joined bodies by a blank
line. ``//`` is a comment only in YARA: a Sigma download did not load as YAML
(``mapping values are not allowed here``) and two Sigma drafts were not a
multi-document stream; a Suricata download started with a line Suricata
reports as a signature parse error. It also served every body, one that does
not compile among them, where the report prints only the rules its print gate
lets through (``analyst_print_gate``).

Driven through the route, because the ``include`` parameter is the route's.
"""

from __future__ import annotations

import uuid
from typing import Any
from unittest.mock import AsyncMock, MagicMock

import pytest
import yaml
from fastapi import FastAPI
from fastapi.testclient import TestClient

from app.api.v1 import reports as module

REPORT_ID = uuid.uuid4()

YARA_PRINTED = 'rule Matched {\n  strings:\n    $s1 = "abc"\n  condition:\n    $s1\n}'
YARA_HASH_ONLY = "rule HashOnly {\n  condition:\n    true\n}"
YARA_BROKEN = "rule Broken {\n  condition:"
SIGMA_ONE = "title: One\nid: 1\nlogsource: {product: windows}\ndetection: {condition: sel}\n"
SIGMA_TWO = "title: Two\nid: 2\nlogsource: {product: windows}\ndetection: {condition: sel}\n"
SURICATA = (
    "# Auto-generated by Malspark for sha256 " + "f" * 64 + "\n"
    'alert dns any any -> any any (msg:"c2"; dns.query; content:"c2.example.com"; '
    "sid:9400001; rev:1;)\n"
)

PRINTED_STANDING = (
    "Precision: its strings match the sample it was drafted from (1 of 1 published strings "
    "found), not its hash alone; not run against any other file (no retro-hunt), so how "
    "often it fires elsewhere is not measured."
)
HASH_ONLY_STANDING = (
    "Not printed in the analyst report: it matches the sample by its sha256 only, not by its "
    "content; its body is in the evidence bundle."
)
BROKEN_STANDING = (
    "Not printed in the analyst report: it does not compile; its body is in the evidence bundle."
)


def _rule(kind: str, name: str, body: str, **extra: Any) -> dict[str, Any]:
    return {
        "kind": kind,
        "name": name,
        "body": body,
        "auto_generated": True,
        "source_evidence": [],
        **extra,
    }


SIGNATURES = [
    _rule(
        "yara",
        "Matched",
        YARA_PRINTED,
        matches_sample=True,
        matched_by=["strings"],
        sample_strings=[{"identifier": "$s1", "offset": 16}],
    ),
    _rule("yara", "HashOnly", YARA_HASH_ONLY, matches_sample=True, matched_by=["sha256"]),
    _rule("yara", "Broken", YARA_BROKEN, compile_error="yara.compile failed: line 3"),
    _rule("sigma", "Sigma one", SIGMA_ONE),
    _rule("sigma", "Sigma two", SIGMA_TWO),
    _rule("suricata", "Suricata", SURICATA),
]


@pytest.fixture
def client() -> TestClient:
    from app.database import get_db
    from app.deps import get_current_user, require_active_user

    report = MagicMock()
    report.id = REPORT_ID
    report.malware_report = {
        "schema_version": "1.0",
        "generated_at": "2026-05-16T00:00:00+00:00",
        "verdict": "Malware",
        "identity": {
            "hashes": {"sha256": "f" * 64},
            "file_name": "sample.exe",
            "file_type": "PE",
            "signing": {"is_signed": False},
        },
        "detection_signatures": SIGNATURES,
        "executive_summary": "",
    }
    service = module.ReportService(db=AsyncMock())
    service.get_report = AsyncMock(return_value=report)  # type: ignore[method-assign]

    app = FastAPI()
    app.include_router(module.router, prefix="/api/v1")
    user = MagicMock(id=uuid.uuid4(), email="op@example.com")
    app.dependency_overrides[get_db] = lambda: AsyncMock()
    app.dependency_overrides[get_current_user] = lambda: user
    app.dependency_overrides[require_active_user] = lambda: user
    app.dependency_overrides[module._get_service] = lambda: service
    return TestClient(app)


def _download(client: TestClient, kind: str, query: str = "") -> str:
    response = client.get(f"/api/v1/reports/{REPORT_ID}/signatures/{kind}{query}")
    assert response.status_code == 200, response.text
    return response.text


class TestTheDefaultIsWhatTheReportPrints:
    def test_yara_serves_only_the_rule_matched_by_its_content(self, client: TestClient) -> None:
        body = _download(client, "yara")
        assert body == f"// Matched\n{YARA_PRINTED}\n"
        yara = pytest.importorskip("yara")
        yara.compile(source=body, includes=False)

    def test_sigma_is_one_yaml_stream_of_its_documents(self, client: TestClient) -> None:
        body = _download(client, "sigma")
        assert body == f"# Sigma one\n{SIGMA_ONE}---\n# Sigma two\n{SIGMA_TWO}"
        assert list(yaml.safe_load_all(body)) == [
            {
                "title": "One",
                "id": 1,
                "logsource": {"product": "windows"},
                "detection": {"condition": "sel"},
            },
            {
                "title": "Two",
                "id": 2,
                "logsource": {"product": "windows"},
                "detection": {"condition": "sel"},
            },
        ]

    def test_suricata_names_its_rule_in_a_hash_comment(self, client: TestClient) -> None:
        body = _download(client, "suricata")
        assert body == f"# Suricata\n{SURICATA}"
        for line in body.splitlines():
            assert line == "" or line.startswith("# ") or line.startswith("alert "), line


class TestAllServesEveryDraftWithItsStanding:
    def test_yara_names_each_draft_and_its_standing(self, client: TestClient) -> None:
        body = _download(client, "yara", "?include=all")
        assert body == (
            f"// Matched\n// {PRINTED_STANDING}\n{YARA_PRINTED}\n\n"
            f"// HashOnly\n// {HASH_ONLY_STANDING}\n{YARA_HASH_ONLY}\n\n"
            f"// Broken\n// {BROKEN_STANDING}\n{YARA_BROKEN}\n"
        )

    def test_sigma_standing_is_a_yaml_comment(self, client: TestClient) -> None:
        standing = (
            "Precision: it selects on values this run publishes or a sandbox recorded; not run "
            "against any other log (no retro-hunt), so how often it fires elsewhere is not "
            "measured."
        )
        body = _download(client, "sigma", "?include=all")
        assert body == (
            f"# Sigma one\n# {standing}\n{SIGMA_ONE}---\n# Sigma two\n# {standing}\n{SIGMA_TWO}"
        )
        assert [doc["title"] for doc in yaml.safe_load_all(body)] == ["One", "Two"]

    def test_an_unknown_include_is_refused(self, client: TestClient) -> None:
        response = client.get(f"/api/v1/reports/{REPORT_ID}/signatures/yara?include=every")
        assert response.status_code == 422


def test_a_name_with_a_line_break_stays_on_its_comment_line() -> None:
    from app.services.report_service import signature_download

    stored = {"kind": "yara", "name": "Evil\nrule Injected { condition: true }", "body": "x"}

    assert signature_download([stored], "yara", "all") == (
        "// Evil rule Injected { condition: true }\n"
        "// Not printed in the analyst report: it was drafted before drafts were run against "
        "their sample, so no match by its content is shown; its body is in the evidence bundle.\n"
        "x\n"
    )
